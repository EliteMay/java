import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
import vm from "node:vm";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const context={window:{}};
vm.runInNewContext(read("learning-support-data.js"),context,{timeout:2000});
const data=context.window.JAVA_SUPPORT_DATA;
assert.ok(data && Object.keys(data).length===17,"2-18 have exactly seventeen optional guides");
let checks=0;
for(let n=2;n<=18;n++){
  const d=data[n], page="lesson"+String(n).padStart(2,"0")+".html";
  assert.ok(d,"No guide for "+n);
  const html=read(page);
  assert.ok(html.includes('src="learning-support-data.js"'),page+" data missing");
  assert.ok(html.includes('src="learning-support.js"'),page+" support script missing");
  assert.ok(html.includes('href="learning-support.css"'),page+" support style missing");
  assert.ok(html.includes('class="hero"'),page+" support insertion point missing");
  assert.ok(html.includes('class="course-nav"'),page+" lesson navigation missing");
  assert.ok(html.includes("① 今日の主役"),page+" original section missing");
  assert.ok(html.includes("④ 自力で書く"),page+" exercises missing");
  assert.ok(html.includes('class="ans"'),page+" solution accordion missing");
  assert.ok(d.title && d.summary && d.connects);
  assert.equal(d.basics.length,3,"3 selective prerequisites for "+n);
  assert.ok(d.basics.every(v=>v.length===2 && v[0].length && v[1].length));
  assert.ok(d.steps.length>=3 && d.snippet.length>15 && !/TODO|PLACEHOLDER/i.test(d.snippet));
  assert.ok(d.choices.length>=2 && Number.isInteger(d.answer) && d.answer>=0 && d.answer<d.choices.length);
  assert.ok(d.question && d.reason);
  assert.ok(existsSync(new URL("../"+d.link.split('#')[0],import.meta.url)),"Missing deep-dive "+d.link);
  checks+=14;
}
const intro=read("start.html"), home=read("index.html"), widget=read("learning-support.js");
assert.ok(home.includes('href="start.html"'));
assert.ok(home.includes("lesson02.html?learn=review"));
assert.ok(intro.includes('lesson02.html?learn=guided'));
assert.ok(intro.includes("System.out.println"));
assert.ok(widget.includes('localStorage.setItem(KEY'));
assert.ok(widget.includes('aria-live'));
assert.ok(widget.includes('button'));
checks+=7;
console.log("Optional Java learning support: "+checks+" checks passed");
